package banking.dao;

import banking.util.BankingException;
import java.io.File;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Connection handling and schema setup. The file-based H2 database keeps data after restart (NFR-10).
 * Tests override the location with -Dbanking.db.url=... so they use an in-memory database.
 */
public final class Database {

    @FunctionalInterface
    public interface Work<T> {
        T run(Connection conn) throws SQLException;
    }

    private static final String URL =
            System.getProperty("banking.db.url", "jdbc:h2:file:./data/bankingdb;AUTO_SERVER=TRUE");

    static {
        new File("data").mkdirs();
    }

    private Database() {
    }

    public static Connection open() throws SQLException {
        return DriverManager.getConnection(URL, "sa", "");
    }

    /** Runs read-only work on its own connection. */
    public static <T> T read(Work<T> work) {
        try (Connection conn = open()) {
            return work.run(conn);
        } catch (SQLException e) {
            throw new BankingException("Database error: " + e.getMessage(), e);
        }
    }

    /**
     * NFR-6: runs the work atomically. Everything commits together, or everything is rolled back.
     */
    public static <T> T inTransaction(Work<T> work) {
        try (Connection conn = open()) {
            conn.setAutoCommit(false);
            try {
                T result = work.run(conn);
                conn.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                conn.rollback();
                throw e;
            }
        } catch (SQLException e) {
            throw new BankingException("Database error: " + e.getMessage(), e);
        }
    }

    /** Creates the tables if they do not exist. Safe to call on every start. */
    public static void initSchema() {
        inTransaction(conn -> {
            try (Statement st = conn.createStatement()) {
                st.execute("CREATE TABLE IF NOT EXISTS customers ("
                        + "customer_id VARCHAR(20) PRIMARY KEY, "
                        + "first_name VARCHAR(60) NOT NULL, "
                        + "surname VARCHAR(60) NOT NULL, "
                        + "address VARCHAR(200) NOT NULL, "
                        + "phone VARCHAR(20) NOT NULL, "
                        + "email VARCHAR(120) NOT NULL)");
                st.execute("CREATE TABLE IF NOT EXISTS users ("
                        + "username VARCHAR(40) PRIMARY KEY, "
                        + "password_hash VARCHAR(255) NOT NULL, "
                        + "customer_id VARCHAR(20) NOT NULL REFERENCES customers(customer_id))");
                st.execute("CREATE TABLE IF NOT EXISTS accounts ("
                        + "account_number VARCHAR(20) PRIMARY KEY, "
                        + "customer_id VARCHAR(20) NOT NULL REFERENCES customers(customer_id), "
                        + "account_type VARCHAR(20) NOT NULL, "
                        + "branch VARCHAR(80) NOT NULL, "
                        + "date_opened TIMESTAMP NOT NULL, "
                        + "balance DECIMAL(15,2) NOT NULL CHECK (balance >= 0), "
                        + "employer_name VARCHAR(120), "
                        + "employer_address VARCHAR(200))");
                st.execute("CREATE TABLE IF NOT EXISTS transactions ("
                        + "txn_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "transaction_id VARCHAR(40) NOT NULL UNIQUE, "
                        + "account_number VARCHAR(20) NOT NULL REFERENCES accounts(account_number), "
                        + "txn_type VARCHAR(20) NOT NULL, "
                        + "amount DECIMAL(15,2) NOT NULL CHECK (amount > 0), "
                        + "txn_date TIMESTAMP NOT NULL, "
                        + "balance_after DECIMAL(15,2) NOT NULL, "
                        + "description VARCHAR(200))");
            }
            return null;
        });
    }
}
